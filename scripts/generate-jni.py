#!/usr/bin/env python3
"""Generate repetitive typed JNI operations and Android variadic entry stubs."""
from pathlib import Path
import re
import argparse

root = Path(__file__).resolve().parent.parent
source = (root / "vm/jni.c").read_text()
implemented = set(re.findall(r"\bj_(\w+)\(", source))
types = [("Object", "jobject", "L"), ("Boolean", "jboolean", "Z"), ("Byte", "jbyte", "B"),
         ("Char", "jchar", "C"), ("Short", "jshort", "S"), ("Int", "jint", "I"),
         ("Long", "jlong", "J"), ("Float", "jfloat", "F"), ("Double", "jdouble", "D")]
lines = ["/* Generated by scripts/generate-jni.py. */"]
assembly = ["// Generated by scripts/generate-jni.py. AAPCS64 varargs -> V entry points.", ".text", ".p2align 2"]

def output(type_name, bits="bits"):
    if type_name == "jobject": return f"local(t, (Ref){bits})"
    if type_name == "jfloat": return f"u2f((uint32_t){bits})"
    if type_name == "jdouble": return f"j_double({bits})"
    return f"({type_name}){bits}"

lines += ["static double j_double(uint64_t bits) { double d; memcpy(&d, &bits, 8); return d; }"]

def varargs(name, ret, params):
    """Save every argument register before replacing the varargs parameter with a va_list pointer."""
    implemented.add(name)
    decl = ", ".join(t + " " + n for t, n in params)
    lines.append(f"extern {ret} j_{name}({decl}, ...);")
    named = len(params)
    assembly.extend([f".globl _j_{name}", f"_j_{name}:", "    sub sp, sp, #256",
                     "    stp x0, x1, [sp, #0]", "    stp x2, x3, [sp, #16]",
                     "    stp x4, x5, [sp, #32]", "    stp x6, x7, [sp, #48]",
                     "    stp q0, q1, [sp, #64]", "    stp q2, q3, [sp, #96]",
                     "    stp q4, q5, [sp, #128]", "    stp q6, q7, [sp, #160]",
                     "    str x30, [sp, #240]", "    add x9, sp, #256", "    str x9, [sp, #192]",
                     "    add x9, sp, #64", "    str x9, [sp, #200]", "    add x9, sp, #192",
                     "    str x9, [sp, #208]", f"    mov w9, #{8 * (named - 8)}",
                     "    str w9, [sp, #216]", "    mov w9, #-128", "    str w9, [sp, #220]",
                     f"    add x{named}, sp, #192", f"    bl _j_{name}V",
                     "    ldr x30, [sp, #240]", "    add sp, sp, #256", "    ret", ""])

for prefix, mode in (("", 0), ("Nonvirtual", 1), ("Static", 2)):
    for name, ret, _ in types + [("Void", "void", "V")]:
        base = f"Call{prefix}{name}Method"
        params = [("JNIEnv *", "env"), ("jclass" if mode == 2 else "jobject", "receiver")]
        if mode == 1: params.append(("jclass", "clazz"))
        params.append(("jmethodID", "id"))
        varargs(base, ret, params)
        for suffix, argtype in (("A", "const jvalue *"), ("V", "va_list")):
            implemented.add(base + suffix)
            decl = ", ".join(t + " " + n for t, n in params + [(argtype, "args")])
            lines += [f"{ret} j_{base}{suffix}({decl}) {{", "    ENTER;"]
            if mode == 1: lines += ["    (void)clazz;"]
            call = f"call_method(t, receiver, id, {'args, NULL' if suffix == 'A' else 'NULL, (struct android_va *)args'}, {mode})"
            if ret == "void": lines += [f"    {call};"]
            else: lines += [f"    uint64_t bits = {call};", f"    return {output(ret)};"]
            lines += ["}"]
varargs("NewObject", "jobject", [("JNIEnv *", "env"), ("jclass", "clazz"), ("jmethodID", "id")])
for suffix, argtype in (("A", "const jvalue *"), ("V", "va_list")):
    implemented.add("NewObject" + suffix)
    lines += [f"jobject j_NewObject{suffix}(JNIEnv *env, jclass clazz, jmethodID id, {argtype} args) {{",
              "    ENTER;", "    jobject result = j_AllocObject(env, clazz);", "    if (!result) return NULL;",
              f"    call_method(t, result, id, {'args, NULL' if suffix == 'A' else 'NULL, (struct android_va *)args'}, 1);",
              "    return t->exception ? NULL : result;", "}"]

for name, ret, code in types:
    for static in (False, True):
        prefix = "Static" if static else ""
        objtype = "jclass" if static else "jobject"
        get, set_ = f"Get{prefix}{name}Field", f"Set{prefix}{name}Field"
        implemented.update([get, set_])
        lines += [f"static {ret} j_{get}(JNIEnv *env, {objtype} value, jfieldID id) {{", "    ENTER;",
                  f"    uint32_t *p = field_address(t, value, id, {int(static)});",
                  f"    uint64_t bits = p ? {'vm_wide(p)' if code in 'JD' else '*p'} : 0;",
                  f"    return {output(ret)};", "}",
                  f"static void j_{set_}(JNIEnv *env, {objtype} value, jfieldID id, {ret} item) {{", "    ENTER;",
                  f"    uint32_t *p = field_address(t, value, id, {int(static)});", "    if (!p) return;"]
        bits = "ref(t, item)" if code == "L" else "f2u(item)" if code == "F" else "d2u(item)" if code == "D" else "(uint64_t)item"
        if code in "JD": lines += [f"    uint64_t bits = {bits}; memcpy(p, &bits, 8);"]
        else: lines += [f"    *p = (uint32_t){bits};"]
        lines += ["}"]
    if code == "L": continue
    arr = ret + "Array"
    methods = [f"New{name}Array", f"Get{name}ArrayElements", f"Release{name}ArrayElements",
               f"Get{name}ArrayRegion", f"Set{name}ArrayRegion"]
    implemented.update(methods)
    lines += [f"static {arr} j_New{name}Array(JNIEnv *env, jsize n) {{", "    ENTER;",
              '    if (n < 0) { vm_throw(t, "Ljava/lang/NegativeArraySizeException;", NULL); return NULL; }',
              f'    return ({arr})local(t, vm_new_array(t, vm_array_class(t->vm, "[{code}"), (uint32_t)n));', "}",
              f"static {ret} *j_Get{name}ArrayElements(JNIEnv *env, {arr} value, jboolean *copy) {{", "    ENTER;",
              f"    if (!array(t, value, '{code}')) return NULL;",
              f"    return j_GetPrimitiveArrayCritical(env, value, copy);", "}",
              f"static void j_Release{name}ArrayElements(JNIEnv *env, {arr} value, {ret} *ptr, jint mode) {{", "    ENTER;",
              f"    if (array(t, value, '{code}')) release(t, ref(t, value), ptr, mode == JNI_COMMIT);", "}",
              f"static void j_Get{name}ArrayRegion(JNIEnv *env, {arr} value, jsize start, jsize n, {ret} *out) {{", "    ENTER;",
              f"    Object *o = array(t, value, '{code}');",
              f"    if (range(t, o, start, n) && n) memcpy(out, o->u.bytes + (size_t)start * sizeof({ret}), (size_t)n * sizeof({ret}));", "}",
              f"static void j_Set{name}ArrayRegion(JNIEnv *env, {arr} value, jsize start, jsize n, const {ret} *in) {{", "    ENTER;",
              f"    Object *o = array(t, value, '{code}');",
              f"    if (range(t, o, start, n) && n) memcpy(o->u.bytes + (size_t)start * sizeof({ret}), in, (size_t)n * sizeof({ret}));", "}"]

aliases = {"GetStringCritical": "GetStringChars", "ReleaseStringCritical": "ReleaseStringChars"}
header = (root / "include/henge/jni.h").read_text().split("struct JNINativeInterface {", 1)[1].split("};", 1)[0]
header = re.sub(r"/\*.*?\*/", "", header, flags=re.S)
entries = []
for declaration in header.split(";"):
    match = re.fullmatch(r"\s*(.*?)\(\*(\w+)\)\((.*?)\)\s*", declaration, re.S)
    if not match: continue
    ret, name, params = match.groups()
    ret = " ".join(ret.split())
    params = [" ".join(p.split()) for p in params.split(",")]
    entries.append((ret, name, params))
    if name in implemented or name in aliases: continue
    decl = ", ".join(t + (" env" if i == 0 else f" p{i}") for i, t in enumerate(params))
    lines += [f"static {ret} j_{name}({decl}) {{", "    ENTER;"]
    lines += [f"    (void)p{i};" for i in range(1, len(params))]
    lines += [f'    vm_throw(t, "Ljava/lang/UnsupportedOperationException;", "JNI {name}");']
    if ret != "void": lines += ["    return " + ("JNI_ERR" if name.startswith("Monitor") else "0") + ";"]
    lines += ["}"]
# Darwin assumes callers extend narrow arguments; AAPCS64 requires the callee to do so.
# Keep incoming GP parameters wide, then narrow at the typed implementation boundary.
for ret, name, params in entries:
    if "..." in params: continue  # dedicated Android assembly entries handle ellipsis
    decl = ", ".join((typ if typ in ("jfloat", "jdouble") else "uint64_t") + f" p{i}" for i, typ in enumerate(params))
    call = ", ".join(f"({typ})p{i}" for i, typ in enumerate(params))
    lines += [f"static {ret} abi_{name}({decl}) {{",
              f"    {'' if ret == 'void' else 'return '}j_{aliases.get(name, name)}({call});", "}"]
lines += ["static const struct JNINativeInterface functions = {"]
for ret, name, params in entries:
    target = f"j_{name}" if "..." in params else f"({ret} (*)({', '.join(params)}))abi_{name}"
    lines += [f"    .{name} = {target},"]
lines += ["};", ""]
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument("--check", action="store_true")
check = parser.parse_args().check
for file, content in (("vm/jni_generated.inc", lines), ("vm/jni_varargs.S", assembly)):
    path, output = root / file, "\n".join(content)
    if check:
        if not path.exists() or path.read_text() != output: parser.exit(1, f"stale {file}; run scripts/generate-jni.py\n")
    else:
        path.write_text(output)

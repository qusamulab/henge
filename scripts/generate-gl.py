#!/usr/bin/env python3
"""Generate the Android -> Darwin GLES boundary, without a build-time network dependency.

Use --registry /path/to/KhronosGroup/OpenGL-Registry/xml/gl.xml to refresh the pinned
signature snapshot. Khronos registry data: Copyright 2013-2026 The Khronos Group Inc.,
SPDX-License-Identifier: Apache-2.0. Only GLES 2.0 / 3.0 core entry points are selected.
"""
import argparse
import hashlib
import json
from pathlib import Path
import xml.etree.ElementTree as ET

root = Path(__file__).resolve().parent.parent
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument("--registry", type=Path)
parser.add_argument("--check", action="store_true")
args = parser.parse_args()
snapshot = root / "scripts/gl-api.json"
if args.registry:
    xml = ET.fromstring(args.registry.read_bytes())
    names = set()
    for feature in xml.findall("feature"):
        if feature.get("api") == "gles2" and float(feature.get("number")) <= 3.0:
            names.update(c.get("name") for c in feature.findall("require/command"))
    commands = []
    for c in xml.findall("commands/command"):
        proto = c.find("proto")
        if proto is None or proto.findtext("name") not in names:
            continue
        def type_of(element):
            return ((element.text or "") + "".join(
                ("" if child.tag == "name" else "".join(child.itertext())) + (child.tail or "")
                for child in element)).strip()
        commands.append(dict(name=proto.findtext("name"), result=type_of(proto),
                             params=[[type_of(p), p.findtext("name")] for p in c.findall("param")]))
    data = dict(source="https://github.com/KhronosGroup/OpenGL-Registry/blob/main/xml/gl.xml",
                sha256=hashlib.sha256(args.registry.read_bytes()).hexdigest(),
                license="Apache-2.0; Copyright 2013-2026 The Khronos Group Inc.",
                commands=sorted(commands, key=lambda c: c["name"]))
    snapshot.write_text(json.dumps(data, indent=2) + "\n")
data = json.loads(snapshot.read_text())
lines = ["/* Generated by scripts/generate-gl.py; do not edit.",
         " * Signatures derived from Khronos gl.xml (Apache-2.0).",
         " * Copyright 2013-2026 The Khronos Group Inc.",
         " * Registry SHA-256: " + data["sha256"] + " */",
         '#include "shim.h"', '#include "henge/henge.h"',
         "#include <dlfcn.h>", "#include <stdatomic.h>", "#include <string.h>",
         "typedef unsigned int GLenum, GLbitfield, GLuint;",
         "typedef int GLint, GLsizei;", "typedef unsigned char GLboolean, GLubyte;",
         "typedef signed char GLbyte;", "typedef short GLshort;", "typedef unsigned short GLushort;",
         "typedef char GLchar;", "typedef float GLfloat, GLclampf;",
         "typedef double GLdouble;", "typedef intptr_t GLintptr, GLsizeiptr;",
         "typedef int64_t GLint64;", "typedef uint64_t GLuint64;", "typedef void *GLsync;",
         "typedef void GLvoid;", "static void *(*g_resolver)(const char *);", ""]
for c in data["commands"]:
    result, name, params = c["result"], c["name"], c["params"]
    fp = sum(t in ("GLfloat", "GLclampf", "GLdouble") for t, _ in params)
    if fp > 8:
        raise ValueError(f"{name}: stack FP arguments need an asm bridge")
    # Widen every GP argument, including those on the stack, to an AAPCS64 eight-byte slot.
    # The typed backend call below re-packs Darwin's stack and extends narrow arguments.
    sig = ", ".join(f"{t if t in ('GLfloat', 'GLclampf', 'GLdouble') else 'uint64_t'} a{i}"
                    for i, (t, _) in enumerate(params)) or "void"
    typed = ", ".join(t for t, _ in params) or "void"
    call = ", ".join(f"({t})a{i}" for i, (t, _) in enumerate(params))
    lines += [f"static _Atomic(void *) target_{name};",
              f"static {result} bridge_{name}({sig}) {{",
              f"    {result} (*fn)({typed}) = ({result} (*)({typed}))atomic_load(&target_{name});",
              f"    {'return ' if result != 'void' else ''}fn({call});", "}"]
lines += ["", "static const struct { const char *name; void *bridge; _Atomic(void *) *target; } entries[] = {"]
for c in data["commands"]:
    name = c["name"]
    lines += [f'    {{"{name}", (void *)bridge_{name}, &target_{name}}},']
lines += ["};", "", "void henge_gl_set_backend(void *(*resolve)(const char *)) { g_resolver = resolve; }",
          "void *hr_gl_lookup(const char *name) {", "    size_t lo = 0, hi = sizeof entries / sizeof entries[0];",
          "    while (lo < hi) {", "        size_t mid = lo + (hi - lo) / 2;",
          "        int cmp = strcmp(name, entries[mid].name);", "        if (!cmp) {",
          "            void *fn = g_resolver ? g_resolver(name) : dlsym(RTLD_DEFAULT, name);",
          "            if (!fn) return NULL;", "            atomic_store(entries[mid].target, fn);",
          "            return entries[mid].bridge;", "        }",
          "        if (cmp < 0) hi = mid; else lo = mid + 1;", "    }", "    return NULL;", "}", ""]
out = root / "runtime/gl_generated.c"
text = "\n".join(lines)
if args.check:
    if not out.exists() or out.read_text() != text:
        raise SystemExit("runtime/gl_generated.c is out of date; run scripts/generate-gl.py")
else:
    out.write_text(text)

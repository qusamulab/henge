#!/usr/bin/env python3
"""Generate the reviewed, ABI-compatible part of the bionic shim. No symbol auto-discovery."""
import argparse
import json
from pathlib import Path
import re

root = Path(__file__).resolve().parent.parent
symbols = json.loads((root / "scripts/libc-api.json").read_text())["symbols"]
assert len({s["name"] for s in symbols}) == len(symbols), "duplicate shim classification"
lines = ["/* Generated by scripts/generate-libc.py from scripts/libc-api.json. */",
         '#include "shim.h"', '#include "linux.h"', '#include <errno.h>', '#include <fenv.h>',
         '#include <math.h>', '#include <stdio.h>', '#include <stdlib.h>',
         '#include <string.h>', '#include <strings.h>', '#include <ctype.h>', '#include <time.h>',
         '#pragma STDC FENV_ACCESS ON']
for s in symbols:
    category, name = s["category"], s["name"]
    if category in ("direct", "handwritten"):
        if category == "handwritten":
            source = (root / s["source"]).read_text()
            assert re.search(r'E\("' + re.escape(name) + r'",', source), f"missing handwritten {name}"
        continue
    assert category in ("errno", "error-code", "math")
    args, ret = s["args"], s["result"]
    call = s.get("call", ", ".join(re.search(r'(\w+)$', a)[1] for a in args))
    lines += [f'static {ret} generated_{name}({", ".join(args)}) {{', '    int saved = hr_errno_begin();']
    if category == "math": lines += ['    fenv_t environment;', '    feholdexcept(&environment);']
    lines += [f'    {"" if ret == "void" else ret + " result = "}{name}({call});']
    if category == "math":
        lines += ['    int exceptions = fetestexcept(FE_INVALID | FE_DIVBYZERO | FE_OVERFLOW | FE_UNDERFLOW);',
                  '    feupdateenv(&environment);',
                  '    if (!errno && (exceptions & FE_INVALID)) errno = EDOM;',
                  '    else if (!errno && exceptions) errno = ERANGE;']
    lines += ['    hr_errno_end(saved);']
    if ret != "void": lines += ['    return hr_errno_to_linux(result);' if category == "error-code" else '    return result;']
    lines += ['}']
lines += ['const struct hr_shim_entry hr_shim_generated[] = {']
for s in symbols:
    if s["category"] != "handwritten":
        lines += [f'    HR_SHIM("{s["name"]}", {s["name"] if s["category"] == "direct" else "generated_" + s["name"]}),']
lines += ['};', 'const size_t hr_shim_generated_count = sizeof hr_shim_generated / sizeof hr_shim_generated[0];', '']
output = "\n".join(lines)
path = root / "runtime/libc_generated.c"
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('--check', action='store_true')
if parser.parse_args().check:
    if not path.exists() or path.read_text() != output: parser.exit(1, "stale libc_generated.c; run scripts/generate-libc.py\n")
else:
    path.write_text(output)

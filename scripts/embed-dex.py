#!/usr/bin/env python3
"""Writes a C source embedding a dex file: embed-dex.py in.dex out.c symbol"""
import sys

data = open(sys.argv[1], "rb").read()
sym = sys.argv[3]
with open(sys.argv[2], "w") as f:
    f.write("/* generated by scripts/embed-dex.py */\n#include <stddef.h>\n#include <stdint.h>\n\n")
    f.write("static const uint8_t data[] = {\n")
    for i in range(0, len(data), 16):
        f.write("    " + ", ".join("0x%02x" % b for b in data[i:i + 16]) + ",\n")
    f.write("};\n\n")
    f.write("const uint8_t *%s(size_t *size)\n{\n    *size = sizeof data;\n    return data;\n}\n" % sym)
